/* Keep the established classic-script scope for file:// and legacy function overrides. */
const fs = require('node:fs');
const path = require('node:path');
const dir = path.join(__dirname, '../assets/js/modules');
const files = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
const output = '/* Generated by tools/build_app.js. Edit assets/js/modules sources. */\n' + files.map(file => {
  if (!/^[a-z0-9-]+\.js$/.test(file)) throw Error('Invalid source name');
  return '\n/* source: '+file+' */\n'+fs.readFileSync(path.join(dir,file),'utf8').replace(/\r\n/g,'\n');
}).join('\n');
const target = path.join(__dirname, '../assets/js/app-bundle.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8')!==output) throw Error('Run node tools/build_app.js to update the application bundle.');
} else fs.writeFileSync(target, output);
console.log('Application bundle: '+files.length+' source modules verified.');
